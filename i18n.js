window.bpT = function bpT(key, vars) {
  const lang = window.bpLang || "en";
  const pack = window.BP_I18N[lang] || window.BP_I18N.en;
  let s = pack[key] != null ? pack[key] : (window.BP_I18N.en[key] || key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return s;
};


/** Apply UI translations on any page that includes this file (library, vitamins, recipes, home). */
window.bpApplyPageI18n = function bpApplyPageI18n() {
  const saved = (function () {
    try { return localStorage.getItem("bp-lang"); } catch (e) { return null; }
  })();
  const lang = window.bpLang || saved || "en";
  window.bpLang = ["en", "es", "pt"].includes(lang) ? lang : "en";
  if (!window.BP_I18N || !window.bpT) return;

  document.documentElement.lang = window.BP_I18N[window.bpLang].htmlLang || window.bpLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = window.bpT(key);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    el.innerHTML = window.bpT(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", window.bpT(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", window.bpT(el.getAttribute("data-i18n-aria")));
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const on = btn.dataset.lang === window.bpLang;
    btn.classList.toggle("is-active", on);
    btn.setAttribute("aria-pressed", String(on));
  });
};

window.bpInitLangSwitch = function bpInitLangSwitch() {
  const root = document.getElementById("lang-switch");
  if (root && !root.dataset.delegated) {
    root.dataset.delegated = "1";
    root.addEventListener("click", (event) => {
      const btn = event.target.closest("button.lang-btn");
      if (!btn) return;
      const lang = btn.getAttribute("data-lang");
      if (!lang || !window.BP_I18N[lang]) return;
      window.bpLang = lang;
      try { localStorage.setItem("bp-lang", lang); } catch (e) {}
      window.bpApplyPageI18n();
    });
  }
  window.bpApplyPageI18n();
};

document.addEventListener("DOMContentLoaded", function () {
  if (document.getElementById("lang-switch")) {
    window.bpInitLangSwitch();
  }
});
